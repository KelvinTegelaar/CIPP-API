# intune-graph-schema.json is generated from the vendored Graph CSDL and shipped twice: the backend validates
# templates against one copy and the template editor types its fields from the other. Both must match a
# fresh run of the generator, or the editor and validation disagree about what a property holds.

BeforeAll {
    $RepoRoot = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSCommandPath)))
    $script:Generator = Join-Path $RepoRoot 'build/tools/Update-IntuneGraphSchema.ps1'
    $script:Committed = @(
        Join-Path $RepoRoot 'backend/Config/intune-graph-schema.json'
        Join-Path $RepoRoot 'frontend/public/intune-graph-schema.json'
    )
    $script:Fresh = Join-Path $TestDrive 'intune-graph-schema.json'
    & $script:Generator -OutputPath $script:Fresh 6> $null
}

Describe 'intune-graph-schema.json' {
    It 'matches a fresh generation from the vendored CSDL (<_>)' -ForEach @(0, 1) {
        $Path = $script:Committed[$_]
        Test-Path $Path | Should -BeTrue -Because "$Path is generated by build/tools/Update-IntuneGraphSchema.ps1"
        [System.IO.File]::ReadAllText($Path).TrimEnd() | Should -BeExactly ([System.IO.File]::ReadAllText($script:Fresh).TrimEnd()) -Because 'run build/tools/Update-IntuneGraphSchema.ps1 after changing the generator or refreshing the Graph metadata'
    }

    It 'types the properties that issue 1421 depends on' {
        $Schema = [System.IO.File]::ReadAllText($script:Fresh) | ConvertFrom-Json -AsHashtable
        $Schema.templateTypes.windowsFeatureUpdateProfiles | Should -Be 'microsoft.graph.windowsFeatureUpdateProfile'
        $FeatureProfile = $Schema.types['microsoft.graph.windowsFeatureUpdateProfile']
        $FeatureProfile.installFeatureUpdatesOptional | Should -Be 'Edm.Boolean'
        $FeatureProfile.rolloutSettings | Should -Be 'microsoft.graph.windowsUpdateRolloutSettings'
        $Schema.types['microsoft.graph.windowsUpdateRolloutSettings'].offerStartDateTimeInUTC | Should -Be 'Edm.DateTimeOffset'
    }
}
